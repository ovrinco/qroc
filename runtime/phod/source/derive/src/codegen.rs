//! Zig code generation from typed Phod ASTs.
//!
//! Converts canonical specs with typed fields and validation constraints
//! into compilable Zig source code. Three spec patterns are supported:
//!
//! - **Validator**: has `validation.*` constraints → `pub fn validate() bool`
//! - **Config**: has typed fields → `pub const Name = struct { ... }`
//! - **Transformer**: has `transform.*` constraints → `pub fn transform() T`

use crate::types::{CanonicalSpec, ConstraintValue};
use crate::{DeriveError, DeriveResult};
use std::fmt::Write;

/// Spec pattern detected from constraints and fields.
#[derive(Debug, Clone, PartialEq)]
pub enum SpecPattern {
    /// Has `validation.*` constraints → generates fn returning bool.
    Validator,
    /// Has typed fields without validation → generates a struct.
    Config,
    /// Has `transform.*` constraints → generates fn returning transformed value.
    Transformer,
}

/// Detect the spec pattern from constraints and fields.
pub fn detect_pattern(spec: &CanonicalSpec) -> Option<SpecPattern> {
    let has_validation = spec
        .constraints
        .keys()
        .any(|k| k.starts_with("validation."));
    let has_transform = spec.constraints.keys().any(|k| k.starts_with("transform."));

    if has_validation {
        Some(SpecPattern::Validator)
    } else if has_transform {
        Some(SpecPattern::Transformer)
    } else if spec.intent.fields.is_some() {
        Some(SpecPattern::Config)
    } else {
        None
    }
}

/// Map a Phod type name to its Zig equivalent.
pub fn phod_to_zig_type(phod_type: &str) -> Result<String, DeriveError> {
    match phod_type {
        "String" => Ok("[]const u8".to_string()),
        "Int" => Ok("i64".to_string()),
        "Bool" => Ok("bool".to_string()),
        _ => {
            if let Some(inner) = phod_type
                .strip_prefix("List<")
                .and_then(|s| s.strip_suffix('>'))
            {
                let zig_inner = phod_to_zig_type(inner)?;
                Ok(format!("[]const {}", zig_inner))
            } else if let Some(inner) = phod_type
                .strip_prefix("Optional<")
                .and_then(|s| s.strip_suffix('>'))
            {
                let zig_inner = phod_to_zig_type(inner)?;
                Ok(format!("?{}", zig_inner))
            } else {
                Err(DeriveError::TypeError {
                    field: phod_type.to_string(),
                    expected: "String, Int, Bool, List<T>, or Optional<T>".to_string(),
                })
            }
        }
    }
}

/// Generate Zig source code from a canonical spec.
pub fn generate_zig(spec: &CanonicalSpec) -> Result<DeriveResult, DeriveError> {
    let pattern = detect_pattern(spec).ok_or_else(|| {
        DeriveError::MissingConstraint(
            "no codegen pattern detected (need validation.* constraints or typed fields)"
                .to_string(),
        )
    })?;

    let content = match pattern {
        SpecPattern::Validator => generate_validator(spec)?,
        SpecPattern::Config => generate_config(spec)?,
        SpecPattern::Transformer => generate_transformer(spec)?,
    };

    Ok(DeriveResult {
        artifact_content: content,
        artifact_filename: format!("{}.zig", spec.intent.name),
        source_hash: spec.source_hash.clone(),
    })
}

// ── Header ────────────────────────────────────────────────────────────

fn write_header(out: &mut String, spec: &CanonicalSpec) -> Result<(), DeriveError> {
    writeln!(out, "// AUTO-GENERATED by phod derivation engine")?;
    writeln!(out, "// spec: {}", spec.intent.name)?;
    writeln!(out, "// purpose: {}", spec.intent.purpose)?;
    writeln!(out, "// source: {}", spec.source_path)?;
    writeln!(out, "// hash: {}", spec.source_hash)?;
    writeln!(out)?;
    writeln!(out, "const std = @import(\"std\");")?;
    writeln!(out)?;
    Ok(())
}

// ── Constraint helpers ───────────────────────────────────────────────

fn get_int_constraint(spec: &CanonicalSpec, key: &str) -> Option<i64> {
    match spec.constraints.get(key) {
        Some(ConstraintValue::Integer(n)) => Some(*n),
        _ => None,
    }
}

fn get_bool_constraint(spec: &CanonicalSpec, key: &str) -> Option<bool> {
    match spec.constraints.get(key) {
        Some(ConstraintValue::Boolean(b)) => Some(*b),
        _ => None,
    }
}

// ── Validator generation ─────────────────────────────────────────────

fn generate_validator(spec: &CanonicalSpec) -> Result<String, DeriveError> {
    let mut out = String::new();
    write_header(&mut out, spec)?;

    // Parameter type from first field, default to String.
    let (param_name, phod_type) = match &spec.intent.fields {
        Some(fields) if !fields.is_empty() => {
            (fields[0].name.as_str(), fields[0].field_type.as_str())
        }
        _ => ("value", "String"),
    };
    let zig_type = phod_to_zig_type(phod_type)?;

    writeln!(out, "pub fn validate({}: {}) bool {{", param_name, zig_type)?;

    // Compile each validation.* constraint into a Zig check.
    let mut count = 0;
    for (key, value) in &spec.constraints {
        if let Some(name) = key.strip_prefix("validation.") {
            if let Some(check) = compile_constraint(name, value, param_name, phod_type)? {
                writeln!(out, "    // constraint: {} = {}", name, value)?;
                writeln!(out, "    {}", check)?;
                count += 1;
            }
        }
    }

    if count == 0 {
        writeln!(out, "    // no validation constraints")?;
    }

    writeln!(out, "    return true;")?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    generate_validator_tests(&mut out, spec, param_name, phod_type)?;
    Ok(out)
}

fn compile_constraint(
    name: &str,
    value: &ConstraintValue,
    param: &str,
    phod_type: &str,
) -> Result<Option<String>, DeriveError> {
    let check = match (name, value, phod_type) {
        ("min_length", ConstraintValue::Integer(n), "String") => {
            Some(format!("if ({}.len < {}) return false;", param, n))
        }
        ("max_length", ConstraintValue::Integer(n), "String") => {
            Some(format!("if ({}.len > {}) return false;", param, n))
        }
        ("not_empty", ConstraintValue::Boolean(true), "String") => {
            Some(format!("if ({}.len == 0) return false;", param))
        }
        ("min", ConstraintValue::Integer(n), "Int") => {
            Some(format!("if ({} < {}) return false;", param, n))
        }
        ("max", ConstraintValue::Integer(n), "Int") => {
            Some(format!("if ({} > {}) return false;", param, n))
        }
        ("equals", ConstraintValue::Boolean(expected), "Bool") => {
            if *expected {
                Some(format!("if (!{}) return false;", param))
            } else {
                Some(format!("if ({}) return false;", param))
            }
        }
        _ => None,
    };
    Ok(check)
}

fn generate_validator_tests(
    out: &mut String,
    spec: &CanonicalSpec,
    _param: &str,
    phod_type: &str,
) -> Result<(), DeriveError> {
    let name = &spec.intent.name;

    let valid = valid_test_value(spec, phod_type);
    writeln!(out, "test \"{}: valid input\" {{", name)?;
    writeln!(out, "    try std.testing.expect(validate({}));", valid)?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    let invalid = invalid_test_value(spec, phod_type);
    writeln!(out, "test \"{}: invalid input\" {{", name)?;
    writeln!(out, "    try std.testing.expect(!validate({}));", invalid)?;
    writeln!(out, "}}")?;

    Ok(())
}

fn valid_test_value(spec: &CanonicalSpec, phod_type: &str) -> String {
    match phod_type {
        "String" => {
            let min_len = get_int_constraint(spec, "validation.min_length").unwrap_or(0) as usize;
            let len = min_len.max(5);
            let s: String = std::iter::repeat('a').take(len).collect();
            format!("\"{}\"", s)
        }
        "Int" => {
            let min = get_int_constraint(spec, "validation.min").unwrap_or(0);
            let max = get_int_constraint(spec, "validation.max").unwrap_or(100);
            format!("{}", (min + max) / 2)
        }
        "Bool" => "true".to_string(),
        _ => "undefined".to_string(),
    }
}

fn invalid_test_value(spec: &CanonicalSpec, phod_type: &str) -> String {
    match phod_type {
        "String" => {
            if let Some(min) = get_int_constraint(spec, "validation.min_length") {
                if min > 1 {
                    let s: String = std::iter::repeat('a').take((min as usize) - 1).collect();
                    return format!("\"{}\"", s);
                }
                return "\"\"".to_string();
            }
            if let Some(max) = get_int_constraint(spec, "validation.max_length") {
                let s: String = std::iter::repeat('a').take((max as usize) + 1).collect();
                return format!("\"{}\"", s);
            }
            if get_bool_constraint(spec, "validation.not_empty") == Some(true) {
                return "\"\"".to_string();
            }
            "\"\"".to_string()
        }
        "Int" => {
            if let Some(min) = get_int_constraint(spec, "validation.min") {
                return format!("{}", min - 1);
            }
            if let Some(max) = get_int_constraint(spec, "validation.max") {
                return format!("{}", max + 1);
            }
            "-1".to_string()
        }
        "Bool" => "false".to_string(),
        _ => "undefined".to_string(),
    }
}

// ── Config/struct generation ─────────────────────────────────────────

fn generate_config(spec: &CanonicalSpec) -> Result<String, DeriveError> {
    let mut out = String::new();
    write_header(&mut out, spec)?;

    let struct_name = to_pascal_case(&spec.intent.name);

    writeln!(out, "pub const {} = struct {{", struct_name)?;
    if let Some(fields) = &spec.intent.fields {
        for field in fields {
            let zig_type = phod_to_zig_type(&field.field_type)?;
            writeln!(out, "    {}: {},", field.name, zig_type)?;
        }
    }
    writeln!(out, "}};")?;
    writeln!(out)?;

    generate_config_test(&mut out, spec, &struct_name)?;
    Ok(out)
}

fn generate_config_test(
    out: &mut String,
    spec: &CanonicalSpec,
    struct_name: &str,
) -> Result<(), DeriveError> {
    writeln!(out, "test \"{}: struct creation\" {{", spec.intent.name)?;
    writeln!(out, "    const instance = {}{{", struct_name)?;
    if let Some(fields) = &spec.intent.fields {
        for field in fields {
            let val = default_zig_value(&field.field_type)?;
            writeln!(out, "        .{} = {},", field.name, val)?;
        }
    }
    writeln!(out, "    }};")?;
    writeln!(out, "    _ = instance;")?;
    writeln!(out, "}}")?;
    Ok(())
}

fn default_zig_value(phod_type: &str) -> Result<String, DeriveError> {
    match phod_type {
        "String" => Ok("\"default\"".to_string()),
        "Int" => Ok("0".to_string()),
        "Bool" => Ok("false".to_string()),
        _ if phod_type.starts_with("List<") => {
            let inner = phod_type
                .strip_prefix("List<")
                .unwrap()
                .strip_suffix('>')
                .unwrap();
            let zig_inner = phod_to_zig_type(inner)?;
            let inner_val = default_zig_value(inner)?;
            Ok(format!("&[_]{}{{{}}}", zig_inner, inner_val))
        }
        _ if phod_type.starts_with("Optional<") => Ok("null".to_string()),
        _ => Err(DeriveError::TypeError {
            field: phod_type.to_string(),
            expected: "String, Int, Bool, List<T>, or Optional<T>".to_string(),
        }),
    }
}

// ── Transformer generation ───────────────────────────────────────────

fn generate_transformer(spec: &CanonicalSpec) -> Result<String, DeriveError> {
    let mut out = String::new();
    write_header(&mut out, spec)?;

    let (param_name, phod_type) = match &spec.intent.fields {
        Some(fields) if !fields.is_empty() => {
            (fields[0].name.as_str(), fields[0].field_type.as_str())
        }
        _ => ("value", "String"),
    };
    let zig_type = phod_to_zig_type(phod_type)?;

    writeln!(
        out,
        "pub fn transform({}: {}) {} {{",
        param_name, zig_type, zig_type
    )?;
    writeln!(out, "    return {};", param_name)?;
    writeln!(out, "}}")?;
    writeln!(out)?;

    writeln!(out, "test \"{}: identity transform\" {{", spec.intent.name)?;
    match phod_type {
        "String" => {
            writeln!(out, "    const result = transform(\"hello\");")?;
            writeln!(
                out,
                "    try std.testing.expectEqualStrings(\"hello\", result);"
            )?;
        }
        "Int" => {
            writeln!(out, "    const result = transform(42);")?;
            writeln!(
                out,
                "    try std.testing.expectEqual(@as(i64, 42), result);"
            )?;
        }
        "Bool" => {
            writeln!(out, "    try std.testing.expect(transform(true));")?;
        }
        _ => {
            writeln!(out, "    _ = transform;")?;
        }
    }
    writeln!(out, "}}")?;

    Ok(out)
}

// ── Utilities ────────────────────────────────────────────────────────

fn to_pascal_case(snake: &str) -> String {
    snake
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => {
                    let upper: String = c.to_uppercase().collect();
                    upper + chars.as_str()
                }
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{IntentSection, TypedField};
    use std::collections::BTreeMap;

    fn make_spec(
        name: &str,
        fields: Option<Vec<TypedField>>,
        extra: Vec<(&str, ConstraintValue)>,
    ) -> CanonicalSpec {
        let mut constraints = BTreeMap::new();
        constraints.insert(
            "target.language".to_string(),
            ConstraintValue::String("zig".to_string()),
        );
        constraints.insert(
            "verification.required_checks".to_string(),
            ConstraintValue::StringList(vec!["compile".to_string()]),
        );
        for (k, v) in extra {
            constraints.insert(k.to_string(), v);
        }
        CanonicalSpec {
            schema_version: 0,
            source_path: format!("test/{}.phod", name),
            source_hash: "sha256:test".to_string(),
            intent: IntentSection {
                name: name.to_string(),
                purpose: "unit test".to_string(),
                behavioral_contracts: None,
                invariants: None,
                fields,
            },
            constraints,
            derived_present: false,
        }
    }

    #[test]
    fn type_mapping_all_primitives() {
        assert_eq!(phod_to_zig_type("String").unwrap(), "[]const u8");
        assert_eq!(phod_to_zig_type("Int").unwrap(), "i64");
        assert_eq!(phod_to_zig_type("Bool").unwrap(), "bool");
    }

    #[test]
    fn type_mapping_parameterized() {
        assert_eq!(
            phod_to_zig_type("List<String>").unwrap(),
            "[]const []const u8"
        );
        assert_eq!(phod_to_zig_type("List<Int>").unwrap(), "[]const i64");
        assert_eq!(phod_to_zig_type("List<Bool>").unwrap(), "[]const bool");
        assert_eq!(phod_to_zig_type("Optional<String>").unwrap(), "?[]const u8");
        assert_eq!(phod_to_zig_type("Optional<Int>").unwrap(), "?i64");
        assert_eq!(phod_to_zig_type("Optional<Bool>").unwrap(), "?bool");
    }

    #[test]
    fn type_mapping_invalid_rejected() {
        assert!(phod_to_zig_type("Float").is_err());
        assert!(phod_to_zig_type("HashMap").is_err());
    }

    #[test]
    fn detect_validator() {
        let spec = make_spec(
            "v",
            None,
            vec![("validation.min_length", ConstraintValue::Integer(1))],
        );
        assert_eq!(detect_pattern(&spec), Some(SpecPattern::Validator));
    }

    #[test]
    fn detect_config() {
        let spec = make_spec(
            "c",
            Some(vec![TypedField {
                name: "x".to_string(),
                field_type: "Int".to_string(),
            }]),
            vec![],
        );
        assert_eq!(detect_pattern(&spec), Some(SpecPattern::Config));
    }

    #[test]
    fn detect_transformer() {
        let spec = make_spec(
            "t",
            None,
            vec![("transform.uppercase", ConstraintValue::Boolean(true))],
        );
        assert_eq!(detect_pattern(&spec), Some(SpecPattern::Transformer));
    }

    #[test]
    fn detect_none() {
        let spec = make_spec("n", None, vec![]);
        assert_eq!(detect_pattern(&spec), None);
    }

    #[test]
    fn pascal_case_conversion() {
        assert_eq!(to_pascal_case("user_config"), "UserConfig");
        assert_eq!(to_pascal_case("hello_world_cli"), "HelloWorldCli");
        assert_eq!(to_pascal_case("minimal"), "Minimal");
    }

    #[test]
    fn default_values_all_types() {
        assert_eq!(default_zig_value("String").unwrap(), "\"default\"");
        assert_eq!(default_zig_value("Int").unwrap(), "0");
        assert_eq!(default_zig_value("Bool").unwrap(), "false");
        assert_eq!(
            default_zig_value("List<String>").unwrap(),
            "&[_][]const u8{\"default\"}"
        );
        assert_eq!(default_zig_value("Optional<Int>").unwrap(), "null");
    }
}
